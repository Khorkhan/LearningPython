# Indentation (การเยื้อง)

x = 1
if x == 1:
    print("X = 1.")

# Explain
# x = 1 (กำหนดค่า)
# = คือการนำค่าไปใส่ในกล่อง
# หมายถึงการเอาเลข 1 ไปใส่ไว้กล่องที่เรียกว่า x
# if x == 1: (การตั้งคำถามและการสั่งงาน)
# if คือคำสั่ง "ถ้า..."
# == คือการเปรียบเทียบว่าทั้ง 2 ฝั่งนี้เท่ากันมั้ย
# ผลลัพธ์ = คำตอบคือ "ใช่" (True) คอมยอมทำคำสั้งบรรทัดต่อไปคือการแสดงข้อความว่า x = 1. ออกมา
# = สั่งเก็บค่า
# == ถามว่าเท่ากันมั้ย

